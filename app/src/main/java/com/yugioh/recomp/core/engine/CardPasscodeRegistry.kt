    private val nameToPasscode = passcodes.entries.associate { it.value.lowercase() to it.key }

    fun findCardNameByPasscode(code: String): String? = passcodes[code.trim().padStart(8, '0')] ?: passcodes[code.trim()]
    fun findPasscodeByCardName(name: String): String? = nameToPasscode[name.trim().lowercase()]
    fun isValidPasscode(code: String): Boolean = passcodes.containsKey(code.trim().padStart(8, '0')) || passcodes.containsKey(code.trim())
